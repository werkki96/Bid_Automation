# 1. 필수 라이브러리 임포트
# ------------------------------------------------------------------------------
import requests
import xml.etree.ElementTree as ET
import pandas as pd
from datetime import datetime, timedelta
import time

# 2. API 요청 및 검색 조건 설정
# ------------------------------------------------------------------------------
# [확인 완료] 정상 작동하는 API 서비스 인증키
SERVICE_KEY = "rbclUUHA4EITbUm3vWbXLisrU8GOSATk8AWiP5/9l4qw90aGZMKycXc6SpUeYZ3Gs+1EbxqeAyjJgxfNSKVsCg=="

# '나라장터 검색조건에 의한 입찰공고 용역조회' End Point URL
URL = "http://apis.data.go.kr/1230000/ad/BidPublicInfoService/getBidPblancListInfoServcPPSSrch"

# 필터링을 원하는 '관심 키워드' 목록
KEYWORDS_TO_SEARCH = ["사이버", "국방", "지휘통제", "AI", "인공지능", "5G", "특화망", "네트워크",]

# 결과에서 제외하고 싶은 '제외 키워드' 목록
EXCLUSION_KEYWORDS = ["청소", "경비", "시설", "관리", "운영", "운전", "폐기물", "공사", "구매", "제작", "전시", "행사", "물품", "보수"]

# 검색 기간 설정 (오늘로부터 14일 전까지)
end_date = datetime.now()
start_date = end_date - timedelta(days=15)

# [확인 완료] API 서버가 인식하는 'YYYYMMDD' 형식으로 날짜 포맷 변경
start_date_str = start_date.strftime('%Y%m%d')
end_date_str = end_date.strftime('%Y%m%d')


# 3. API 호출 및 데이터 수집/필터링
# ------------------------------------------------------------------------------
print("나라장터에서 '용역' 분야 맞춤형 연구과제 탐색을 시작합니다...")
print(f" - 탐색 기간: {start_date.strftime('%Y-%m-%d')} ~ {end_date.strftime('%Y-%m-%d')}")
print(f" - 관심 키워드: {', '.join(KEYWORDS_TO_SEARCH)}\n")

# 필터링 전 모든 결과를 저장할 리스트
all_bid_items = []

# 각 키워드별로 API를 호출하여 서버에서 직접 필터링합니다.
for keyword in KEYWORDS_TO_SEARCH:
    print(f"▶ '{keyword}' 키워드로 검색 중...")

    params = {
        'serviceKey': SERVICE_KEY,
        'pageNo': '1',
        'numOfRows': '100',
        'inqryDiv': '1',
        'inqryBgnDt': start_date_str,
        'inqryEndDt': end_date_str,
        'bidNtceNm': keyword
    }

    try:
        response = requests.get(URL, params=params, timeout=30)
        response.raise_for_status()
        root = ET.fromstring(response.content)

        if root.tag == 'response' and root.findtext('header/resultCode') == '00':
            body = root.find('body')
            items = body.find('items')
            total_count = int(body.findtext('totalCount', '0'))

            if total_count > 0 and items is not None:
                print(f"  ㄴ API가 {total_count}건을 반환했습니다. 2차 필터링 시작...")
                for item in items.findall('item'):
                    bid_title = item.findtext('bidNtceNm', '')

                    if any(ex_keyword in bid_title for ex_keyword in EXCLUSION_KEYWORDS):
                        continue

                    bid_close_date_str = item.findtext('bidClseDt')
                    if bid_close_date_str:
                        try:
                            bid_close_date = datetime.strptime(bid_close_date_str, '%Y-%m-%d %H:%M:%S')
                            if bid_close_date < datetime.now():
                                continue
                        except ValueError:
                            pass

                    price_str = item.findtext('presmptPrce', '0')
                    bid_data = {
                        '검색 키워드': keyword,
                        '공고명': bid_title,
                        '수요기관': item.findtext('dminsttNm'),
                        '추정가격(원)': f"{int(price_str):,}" if price_str and price_str.isdigit() else "가격 정보 없음",
                        '입찰마감일': item.findtext('bidClseDt'),
                        '상세보기': item.findtext('bidNtceDtlUrl')
                    }
                    all_bid_items.append(bid_data)
            else:
                 print("  ㄴ API가 0건을 반환했습니다. (검색 결과 없음)")
        else:
            error_msg = root.findtext('header/resultMsg') if root.find('header') is not None else "알 수 없는 오류 형식"
            print(f"  ㄴ API 응답 오류: {error_msg}")

        time.sleep(0.3)

    except Exception as e:
        print(f"  '{keyword}' 검색 중 오류 발생: {e}")


# 4. 최종 결과 출력
# ------------------------------------------------------------------------------
print("\n" + "="*60)
print(" 최종 탐색 결과")
print("="*60)

if not all_bid_items:
    print("탐색된 과제가 없습니다.")
else:
    # 데이터프레임으로 변환
    df = pd.DataFrame(all_bid_items)

    # [개선] '공고명'을 기준으로 중복된 행을 제거합니다.
    df.drop_duplicates(subset=['공고명'], keep='first', inplace=True)

    # [개선] 인덱스를 1부터 시작하도록 설정합니다.
    df.reset_index(drop=True, inplace=True)
    df.index = df.index + 1

    # 최종 표시에 필요한 컬럼만 선택하고 순서를 지정합니다.
    cols = ['검색 키워드', '공고명', '수요기관', '추정가격(원)', '입찰마감일', '상세보기']
    df = df[cols]

    pd.set_option('display.max_rows', 500)
    pd.set_option('display.max_columns', 500)
    pd.set_option('display.width', 150)
    pd.set_option('display.max_colwidth', 50)

    print(f"총 {len(df)}건의 맞춤형 과제를 찾았습니다.")
    with open('output.csv', 'w', encoding='utf-8-sig', newline='') as output_file:
        df.to_csv(output_file)