#   2. 수집된 데이터에서 마감일이 지난 공고를 1차로 제거
#   3. '제외 키워드'가 포함된 공고를 2차로 제거
#   4. 중복을 제거한 최종 결과를 데이터프레임(표)으로 시각화하여 출력
